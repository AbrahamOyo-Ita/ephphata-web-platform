import { Info } from "lucide-react";
import { DEMO_MODE } from "@/lib/demo";

/**
 * Persistent, unmissable notice that this deployment carries seeded
 * demonstration data. A host should never mistake demo figures for live ones.
 *
 * Renders NOTHING when DEMO_MODE=false, so a production deployment is clean.
 */
export function DemoBanner({ compact = false }: { compact?: boolean }) {
  if (!DEMO_MODE) return null;

  if (compact) {
    return (
      <div className="inline-flex items-center gap-1.5 rounded-xs border border-gold-500/40 bg-gold-500/10 px-2.5 py-1">
        <Info className="h-3 w-3 text-gold-700" strokeWidth={2.4} />
        <span className="text-[0.625rem] font-semibold uppercase tracking-wide text-gold-700">
          Demo data
        </span>
      </div>
    );
  }

  return (
    <div className="flex items-start gap-3 rounded-sm border border-gold-500/35 bg-gold-500/[0.08] px-4 py-3">
      <Info className="mt-0.5 h-4 w-4 shrink-0 text-gold-700" strokeWidth={2.2} />
      <div className="text-[0.75rem] leading-relaxed text-ink-700">
        <p className="font-semibold">
          Demonstration dataset
          <span className="ml-2 rounded bg-gold-500/25 px-1.5 py-0.5 text-[0.5625rem] font-bold uppercase tracking-wide text-gold-700">
            Not live
          </span>
        </p>
        <p className="mt-0.5 text-ink-500">
          Registrations, volunteers and prayer requests below were generated by{" "}
          <code className="rounded bg-white/70 px-1 py-0.5 font-mono text-[0.6875rem]">scripts/seed.mjs</code>{" "}
          for this presentation. Real submissions you create during the demo land in the same tables
          and behave identically.
        </p>
      </div>
    </div>
  );
}
